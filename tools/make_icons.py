"""Generate the Smart Home app icons and the C header embedded in the sketch."""
from pathlib import Path
from PIL import Image, ImageDraw

S = 2048          # supersampled working canvas
K = S / 512.0     # scale from the 512x512 design coordinates

def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

def gradient(size, c0, c1, diagonal=True):
    small = Image.new("RGB", (16, 16))
    px = small.load()
    for y in range(16):
        for x in range(16):
            t = (x + y) / 30.0 if diagonal else y / 15.0
            px[x, y] = lerp(c0, c1, t)
    return small.resize((size, size), Image.BICUBIC)

# Background
bg = gradient(S, (0x15, 0x1d, 0x30), (0x0b, 0x0f, 0x19))
mask = Image.new("L", (S, S), 0)
ImageDraw.Draw(mask).rounded_rectangle([0, 0, S - 1, S - 1], radius=110 * K, fill=255)
icon = Image.new("RGBA", (S, S), (0, 0, 0, 0))
icon.paste(bg, (0, 0), mask)

# Thin cyan inner border (30% opacity)
border = Image.new("RGBA", (S, S), (0, 0, 0, 0))
ImageDraw.Draw(border).rounded_rectangle(
    [12 * K, 12 * K, S - 12 * K, S - 12 * K],
    radius=100 * K, outline=(0x38, 0xbd, 0xf8, 77), width=round(8 * K))
icon.alpha_composite(border)

# House silhouette (roof + walls, with a doorway notch)
house_pts = [
    (256, 90), (80, 230), (120, 230), (120, 410), (210, 410),
    (210, 300), (302, 300), (302, 410), (392, 410), (392, 230), (432, 230),
]
house_mask = Image.new("L", (S, S), 0)
ImageDraw.Draw(house_mask).polygon([(x * K, y * K) for x, y in house_pts], fill=255)
roof = gradient(S, (0x38, 0xbd, 0xf8), (0x02, 0x84, 0xc7))
icon.paste(roof, (0, 0), house_mask)

# Green status dot with a white plus
d = ImageDraw.Draw(icon)
cx, cy, r = 256 * K, 220 * K, 38 * K
d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(0x22, 0xc5, 0x5e, 255))
w = 6 * K
d.line([cx - 10 * K, cy, cx + 10 * K, cy], fill=(255, 255, 255, 255), width=round(w))
d.line([cx, cy - 10 * K, cx, cy + 10 * K], fill=(255, 255, 255, 255), width=round(w))

icon = icon.convert("RGB")
outdir = Path("icons")
outdir.mkdir(exist_ok=True)
sizes = {"icon-512.png": 512, "icon-192.png": 192, "apple-touch-icon.png": 180}
images = {}
for name, size in sizes.items():
    img = icon.resize((size, size), Image.LANCZOS)
    img.save(outdir / name, optimize=True)
    images[name] = (img, (outdir / name).read_bytes())
    print(name, (outdir / name).stat().st_size, "bytes")

# C header
def carray(name, data, per_line=20):
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)

header = [
    "#pragma once",
    "#include <Arduino.h>",
    "",
    "// Generated by tools/make_icons.py - do not edit by hand.",
    "",
]
for name, key in [("ICON_512", "icon-512.png"), ("ICON_192", "icon-192.png"), ("ICON_180", "apple-touch-icon.png")]:
    data = images[key][1]
    header.append(f"const unsigned int {name}_LEN = {len(data)};")
    header.append(carray(name, data))
    header.append("")
Path("app_icons.h").write_text("\n".join(header), encoding="utf-8")
print("wrote app_icons.h", Path("app_icons.h").stat().st_size, "bytes")
